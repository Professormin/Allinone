#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Geek Empire Skill v0.2 - Unified Protocol & Ingestion Module
Handles geek-empire/1.0 protocol handoff packages, multi-topic extraction,
dual-mode archiving (Reviewed vs Quick/Inbox), idempotency checking,
and safe atomic vault ingestion.
"""

import argparse
import datetime
import glob
import json
import os
import re
import sys
import uuid

# Load existing archive and index modules
sys.path.insert(0, os.path.dirname(__file__))
import archive
import update_index

PROTOCOL_VERSION = "geek-empire/1.0"


def generate_handoff_id():
    """Generate a unique handoff ID for protocol deduplication."""
    return f"GEH-{uuid.uuid4().hex[:8].upper()}"


def generate_batch_id():
    """Generate a shared batch ID for multi-topic split conversations."""
    today = datetime.datetime.now().strftime("%Y%m%d")
    return f"GEB-{today}-{uuid.uuid4().hex[:4].upper()}"


def create_handoff_package(
    title,
    background,
    verified_summary="",
    verified_code="",
    unverified_summary="无",
    failed_summary="无",
    failed_details="无",
    pending_summary="无",
    sop_steps="",
    user_intent_cleaned="",
    requirements_revision="",
    fuzzy_search_hints="",
    lessons_learned="",
    category="01_AI工具与工作流",
    keywords=None,
    review_status="unreviewed",
    verification_status="verified",
    source_ai="unknown",
    batch_id=None,
    handoff_id=None,
    tags=None,
    priority="normal",
    pinned_quote=None
):
    """
    Creates a standard geek-empire/1.0 handoff JSON package or Markdown string.
    Can be generated by any compatible AI model. Supports Pinned Insights.
    """
    if not handoff_id:
        handoff_id = generate_handoff_id()
    if not batch_id:
        batch_id = generate_batch_id()

    if keywords is None:
        keywords = []
    if isinstance(keywords, str):
        keywords = [k.strip() for k in keywords.split(",") if k.strip()]

    if tags is None:
        tags = keywords

    pkg = {
        "protocol": PROTOCOL_VERSION,
        "handoff_id": handoff_id,
        "batch_id": batch_id,
        "title": title,
        "category": category,
        "priority": priority, # normal / high
        "review_status": review_status.lower(),
        "verification_status": verification_status.lower(),
        "source_ai": source_ai,
        "keywords": keywords,
        "tags": tags,
        "created_at": datetime.datetime.now().strftime("%Y-%m-%d"),
        "payload": {
            "background": background,
            "verified_summary": verified_summary,
            "verified_code": verified_code,
            "unverified_summary": unverified_summary,
            "failed_summary": failed_summary,
            "failed_details": failed_details,
            "pending_summary": pending_summary,
            "sop_steps": sop_steps,
            "user_intent_cleaned": user_intent_cleaned,
            "requirements_revision": requirements_revision,
            "fuzzy_search_hints": fuzzy_search_hints,
            "lessons_learned": lessons_learned,
            "pinned_quote": pinned_quote
        }
    }
    return pkg


def check_handoff_exists(vault_path, handoff_id):
    """
    Scans vault and inbox to check if a handoff_id has already been ingested
    for idempotency deduplication.
    """
    if not handoff_id or not os.path.exists(vault_path):
        return False, None

    pattern = os.path.join(vault_path, "**", "*.md")
    regex = re.compile(rf'handoff_id:\s*["\']?{re.escape(handoff_id)}["\']?')

    for filepath in glob.glob(pattern, recursive=True):
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                content = f.read(2000)
                if regex.search(content):
                    return True, filepath
        except Exception:
            continue

    return False, None


def ingest_handoff_package(vault_path, package_data, force_review=False):
    """
    Ingests a geek-empire/1.0 handoff package atomically.
    - Validates protocol version.
    - Checks handoff_id for idempotency.
    - Routes to '00_INBOX' if review_status == 'unreviewed', otherwise to official Category folder.
    - Atomically writes file and updates INDEX.md / CATALOG.csv.
    """
    vault_path = os.path.abspath(vault_path)
    os.makedirs(vault_path, exist_ok=True)

    # 1. Protocol Version Check
    protocol = package_data.get("protocol")
    if protocol != PROTOCOL_VERSION:
        raise ValueError(f"Unsupported protocol version '{protocol}'. Expected '{PROTOCOL_VERSION}'")

    handoff_id = package_data.get("handoff_id", generate_handoff_id())
    batch_id = package_data.get("batch_id", generate_batch_id())

    # 2. Idempotency Check
    exists, existing_file = check_handoff_exists(vault_path, handoff_id)
    if exists and existing_file:
        print(f"Notice: Handoff package {handoff_id} already ingested at: {existing_file}")
        return existing_file, "ALREADY_EXISTS"

    # Extract Fields
    title = package_data.get("title", "Untitled Knowledge Asset")
    category = package_data.get("category", "01_AI工具与工作流")
    priority = package_data.get("priority", "normal")
    review_status = package_data.get("review_status", "unreviewed").lower()
    if force_review:
        review_status = "reviewed"

    verification_status = package_data.get("verification_status", "verified").lower()
    source_ai = package_data.get("source_ai", "unknown")
    keywords = package_data.get("keywords", [])
    payload = package_data.get("payload", {})

    # 3. Determine Routing Directory (Inbox vs Official Category)
    # If pinned insight or unreviewed, route to '_INBOX'
    if review_status == "unreviewed" or priority == "high":
        target_category_dir = os.path.join(vault_path, "_INBOX")
    else:
        target_category_dir = os.path.join(vault_path, category)

    os.makedirs(target_category_dir, exist_ok=True)

    # 4. Doc ID Allocation
    doc_id = archive.get_next_doc_id(vault_path)

    # File naming
    safe_title = re.sub(r'[\\/*?:"<>|]', '_', title).replace(' ', '_')
    filename = f"{doc_id}_{safe_title}.md"
    target_file = os.path.join(target_category_dir, filename)

    # 5. Build Content using Template
    skill_root_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    template_str = archive.load_template(skill_root_dir)

    today_str = datetime.datetime.now().strftime("%Y-%m-%d")
    formatted_keywords = ", ".join([f'"{k}"' for k in keywords])
    formatted_tags = ", ".join([f'"{t}"' for t in package_data.get("tags", keywords)])

    replacements = {
        "{{DOC_ID}}": doc_id,
        "{{HANDOFF_ID}}": handoff_id,
        "{{BATCH_ID}}": batch_id,
        "{{TITLE}}": title,
        "{{CREATED_AT}}": today_str,
        "{{UPDATED_AT}}": today_str,
        "{{CATEGORY}}": category,
        "{{REVIEW_STATUS}}": review_status,
        "{{VERIFICATION_STATUS}}": verification_status,
        "{{SOURCE_AI}}": source_ai,
        "{{KEYWORDS}}": formatted_keywords,
        "{{TAGS}}": formatted_tags,
        "{{BACKGROUND}}": payload.get("background", "无问题背景。"),
        "{{VERIFIED_SUMMARY}}": payload.get("verified_summary", "方案已验证通过。"),
        "{{UNVERIFIED_SUMMARY}}": payload.get("unverified_summary", "无"),
        "{{FAILED_SUMMARY}}": payload.get("failed_summary", "无"),
        "{{PENDING_SUMMARY}}": payload.get("pending_summary", "无"),
        "{{VERIFIED_CODE}}": payload.get("verified_code", "# 命令已校验"),
        "{{SOP_STEPS}}": payload.get("sop_steps", "按上述代码指示操作即可。"),
        "{{USER_INTENT_CLEANED}}": payload.get("user_intent_cleaned", "用户表达需求已忠实清理保存。"),
        "{{REQUIREMENTS_REVISION}}": payload.get("requirements_revision", "无需求变更或修正历史。"),
        "{{FUZZY_SEARCH_HINTS}}": payload.get("fuzzy_search_hints", ", ".join(keywords)),
        "{{LESSONS_LEARNED}}": payload.get("lessons_learned", "可以直接复用于同类场景。")
    }

    doc_content = template_str
    for k, v in replacements.items():
        doc_content = doc_content.replace(k, str(v))

    # 6. Atomic File Write (write to .tmp first, then replace)
    tmp_file = target_file + ".tmp"
    try:
        with open(tmp_file, "w", encoding="utf-8") as f:
            f.write(doc_content)
        os.replace(tmp_file, target_file)
    except Exception as e:
        if os.path.exists(tmp_file):
            os.remove(tmp_file)
        raise IOError(f"Atomic file write failed: {e}")

    print(f"✅ Ingested Handoff Package [{handoff_id}] -> {target_file}")

    # 7. Sync INDEX.md and CATALOG.csv
    try:
        update_index.update_catalog_and_index(vault_path)
    except Exception as e:
        print(f"Warning: Index update failed: {e}", file=sys.stderr)

    return target_file, doc_id


def promote_inbox_item(vault_path, doc_id_or_file):
    """
    Promotes an unreviewed item in _INBOX/ to official reviewed category
    without generating a duplicate document ID.
    """
    vault_path = os.path.abspath(vault_path)
    inbox_dir = os.path.join(vault_path, "_INBOX")

    if not os.path.exists(inbox_dir):
        print(f"Notice: Inbox directory does not exist: {inbox_dir}")
        return False

    # Find the file in _INBOX
    target_file = None
    if os.path.exists(doc_id_or_file) and doc_id_or_file.startswith(inbox_dir):
        target_file = doc_id_or_file
    else:
        candidates = glob.glob(os.path.join(inbox_dir, f"{doc_id_or_file}_*.md"))
        if candidates:
            target_file = candidates[0]

    if not target_file or not os.path.exists(target_file):
        print(f"Error: Target inbox item '{doc_id_or_file}' not found in _INBOX.")
        return False

    # Read content
    with open(target_file, "r", encoding="utf-8") as f:
        content = f.read()

    # Extract category
    cat_match = re.search(r'category:\s*["\']?([^"\']+)["\']?', content)
    category = cat_match.group(1) if cat_match else "01_AI工具与工作流"

    # Move to official category directory
    official_dir = os.path.join(vault_path, category)
    os.makedirs(official_dir, exist_ok=True)

    filename = os.path.basename(target_file)
    official_file = os.path.join(official_dir, filename)

    # Update review_status in content to 'reviewed'
    content_updated = re.sub(r'review_status:\s*["\']?unreviewed["\']?', 'review_status: "reviewed"', content)

    # Write official file and remove inbox file
    with open(official_file, "w", encoding="utf-8") as f:
        f.write(content_updated)

    os.remove(target_file)
    print(f"✅ Promoted Inbox Item -> Official Vault: {official_file}")

    # Sync Index
    update_index.update_catalog_and_index(vault_path)
    return official_file


def main():
    parser = argparse.ArgumentParser(description="Geek Empire Handoff Protocol Ingestion Tool")
    parser.add_argument("--vault-path", default=os.environ.get("GEEK_EMPIRE_PATH", os.getcwd()), help="Path to vault")
    parser.add_argument("--input-json", help="Path to geek-empire/1.0 handoff JSON file")
    parser.add_argument("--promote", help="Doc ID or filename in _INBOX to promote to official vault")

    args = parser.parse_args()

    if args.promote:
        promote_inbox_item(args.vault_path, args.promote)
    elif args.input_json:
        with open(args.input_json, "r", encoding="utf-8") as f:
            pkg = json.load(f)
            ingest_handoff_package(args.vault_path, pkg)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
